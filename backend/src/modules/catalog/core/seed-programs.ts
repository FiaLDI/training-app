import type {
  ProgramSnapshot,
  SnapshotExercise,
  SnapshotProgramDay,
} from '../../program/core/lib/program-snapshot'

export type CatalogProgramSeed = {
  id: string
  slug: string
  name: string
  author: string
  description: string
  tags: string[]
  sortOrder: number
  snapshot: ProgramSnapshot
}

function ex(
  exerciseName: string,
  targetSets: number,
  minReps: number,
  maxReps: number,
  order: number,
  notes?: string,
): SnapshotExercise {
  return {
    exerciseName,
    exerciseOrder: order,
    targetSets,
    minReps,
    maxReps,
    notes: notes ?? null,
  }
}

function day(
  dayOfWeek: number,
  name: string,
  description: string,
  exercises: SnapshotExercise[],
): SnapshotProgramDay {
  return {
    dayOfWeek,
    slotOrder: 0,
    notes: null,
    template: { name, description, exercises },
  }
}

